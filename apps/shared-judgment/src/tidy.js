/* tidy.js —— 断辞原文的**清洗**（模型吐出来的那段字的最后一道收口）
 *
 *   实测结论：**不是渲染层改的字**。把那段原文逐字喂进 renderDoc，输出与原文一致 ——
 *   那些 0 / 5 / ! / ; 是**模型自己输出的半角噪声**（同一段落里三处，说明不是偶发）。
 *   渲染层能做的只有两件事：① 把半角标点收回中文全角（可读性）；
 *   ② 把明显是噪声的孤立半角数字去掉（"不小5小" → "不小小"）。
 *   ⚠ 改不动的是「字被模型写坏」的部分（如「面试；试」多出来一个"试"）——
 *     那就不是清洗能修的，只能靠换模型/换参数。
 *
 * 只处理标点与孤立数字，**不碰任何判据文义**，改前改后句子含义不变。
 */

/* 汉字区：基本区 + 扩展 A + 兼容区（够用；不用 \p{Script=Han}，省得老引擎嫌新） */
const CJK = '\\u3400-\\u4dbf\\u4e00-\\u9fff\\uf900-\\ufaff';
const RE_DIGIT_IN_CJK = new RegExp('([' + CJK + '])[0-9]([' + CJK + '])', 'g');
/* 「小5小」这种：数字两边同一个字 ⇒ 数字是噪声、后面那个字是重写 ⇒ 收成一个字 */
const RE_DIGIT_BETWEEN_SAME = new RegExp('([' + CJK + '])[0-9]\\1', 'g');
/* 行首（可带 markdown 的 ** ）紧跟一个数字再接汉字：如你截图里那条「0能通过」 */
const RE_LEAD_DIGIT = new RegExp('^(\\*\\*\\s*)?[0-9](?=[' + CJK + '])', 'gm');
const RE_HALF_PUNCT_AFTER_CJK = new RegExp('([' + CJK + '])([,;:!?])', 'g');

const FULL = { ',': '，', ';': '；', ':': '：', '!': '！', '?': '？' };

/**
 * 清洗一段断辞原文。**幂等**：同一段跑两遍结果不变（渲染每来一个增量都会重跑）。
 * @param {string} t 模型原文 / 本机速断正文
 * @returns {string}
 */
export function tidyDuanci(t) {
  let s = String(t == null ? '' : t);
  if (!s) return s;
  const before = s;

  /* ① 零宽字符与方向控制符（复制粘贴、某些服务商的分词里会夹带，肉眼看不见但会顶字距） */
  s = s.replace(/[\u200b-\u200f\u2028-\u202e\ufeff]/g, '');

  /* ② 夹在两个字中间的**单个**半角数字：几乎只能是噪声（"精力消耗不小5小" → "…不小"）。
        分两步：
          ②a 数字两边是**同一个字** ⇒ 数字是噪声、后面那个字是重写 ⇒ 收成一个（"小5小" → "小"）；
          ②b 其余情况只把数字摘掉（"不5小" → "不小"）。
        判定刻意收紧：左右都得是汉字、且只吃一位 —— 这样「3 天」「2 到 4 月」这种带空格的取数不受影响，
        "1,000" 这种数字串也不会被拆。 */
  for (let i = 0; i < 3; i++) {
    const next = s.replace(RE_DIGIT_BETWEEN_SAME, '$1').replace(RE_DIGIT_IN_CJK, '$1$2');
    if (next === s) break;
    s = next;
  }

  /* ②c 行首那个孤零零的数字（你截图里「0能通过」就是这种）。只吃**行首**这一位：
        应期里的「3 天」「5 月」都在句子中间，不会碰到。 */
  s = s.replace(RE_LEAD_DIGIT, '$1');

  /* ③ 汉字后紧跟的半角标点 → 全角（"，"→"，"、"!"→"！"…）。
        只在**前面是汉字**时收：所以英文/代码/数字里的半角原样不动。 */
  s = s.replace(RE_HALF_PUNCT_AFTER_CJK, (m, a, p) => a + FULL[p]);

  /* ④ 重复的全角逗号/句号收成一个（流式拼接偶尔会抖出"，，"） */
  s = s.replace(/，{2,}/g, '，').replace(/。{2,}/g, '。');

  /* ⑤ 行首尾空白（不改行数：renderDoc 拿空行当段距） */
  s = s.replace(/[ \t\u3000]+$/gm, '');

  return s;
}

export const Tidy = { tidyDuanci };
