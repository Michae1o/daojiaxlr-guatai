/* 认平台（不看窗口宽度） */
export function faqPlatform() {
  var w = (typeof window !== 'undefined') ? window : {};
  if (w.__TAURI__) return 'win';
  var C = w.Capacitor;
  try {
    if (C && typeof C.isNativePlatform === 'function' && C.isNativePlatform()) return 'and';
    if (C && typeof C.getPlatform === 'function' && C.getPlatform() !== 'web') return 'and';
  } catch (e) { }
  try {
    if (/Android/i.test(navigator.userAgent) && /\bwv\b/.test(navigator.userAgent)) return 'and';
  } catch (e) { }
  return 'web';
}

/* 本平台该显示的那几条：本端专属 + 通用（顺序保持原表顺序） */
export function faqList() {
  var p = faqPlatform();
  return ITEMS.filter(function (it) { return it.p === 'all' || it.p === p; });
}
